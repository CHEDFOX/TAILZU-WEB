// Writes js/blip/moves.js: the few of Blip's moves the page's small bots use, sampled from the desktop app's catalog.
//
// The desktop plays Blip's moves from a catalog compiled at run time by its motion language (botTiles.js, 445 KB),
// which the page has no need to carry for three small bots. So the moves are played here once, in Node, and kept as
// frames: the card poses he peeks over an edge in (hidden, peek, crane) as they are, and each gesture sampled at FPS,
// every number rounded, for js/minis.js to put back into blip.js's tables.
//
//   node scripts/gen-blip-moves.mjs [path to TAILZU-DESKTOP]     (default: ../TAILZU-DESKTOP beside this repo)
//
// Run it again when Blip's catalog changes (TAILZU-BACKEND shared/bots/blip.json) or js/blip/blip.js is copied anew.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const here = path.dirname(new URL(import.meta.url).pathname);
const desk = path.resolve(process.argv[2] || path.join(here, "../../TAILZU-DESKTOP"));
const require = createRequire(import.meta.url);
globalThis.window = globalThis;
require(path.join(desk, "botTiles.js"));
require(path.join(desk, "src/shared/blipCatalog.js"));
require(path.join(desk, "src/shared/blipStarter.js"));
const B = require(path.join(desk, "src/shared/blip.js"));

const FPS = 24;
// name → [seconds sampled, how it plays]: "loop" (balance comes back to where it started), "bounce" (forwards then back,
// for the idle moves that never quite repeat), or "once" (a flip with a hop, a laugh, a wave).
const PICK = {
  balance: [B.GESTURE_LENGTH.balance, "loop"], rest: [4, "bounce"], tiptoe: [B.GESTURE_LENGTH.tiptoe, "bounce"],
  celebrate: [B.GESTURE_LENGTH.celebrate, "once"], laugh: [B.GESTURE_LENGTH.laugh, "once"], done: [B.GESTURE_LENGTH.done, "once"],
};

const r3 = (v) => Math.round(v * 1000) / 1000;
const NUM = Object.keys(B.gesturePose("balance", 0, 0)).filter((k) => typeof B.gesturePose("balance", 0, 0)[k] === "number");
const STR = ["mouth", "eye"];
// one frame → one flat row: the numbers, then the arms, the eye's look and the legs, then the strings
function row(p) {
  return [...NUM.map((k) => r3(p[k] ?? 0)), ...p.ra.map(r3), ...p.la.map(r3), ...p.look.map(r3),
    ...p.legs.flatMap((l) => [r3(l.th), r3(l.lift)]), ...STR.map((k) => p[k] ?? "")];
}
const moves = {};
for (const [name, [len, play]] of Object.entries(PICK)) {
  const n = Math.max(2, Math.round(len * FPS) + 1), frames = [];
  for (let i = 0; i < n; i++) frames.push(row(B.gesturePose(name, (i / (n - 1)) * len, 0)));
  moves[name] = { len: r3(len), play, frames };
}
const card = {};
for (const k of ["hidden", "peek", "crane"]) card[k] = B.POSES[k];

const out = `// GENERATED by scripts/gen-blip-moves.mjs from the desktop app's Blip catalog: do not edit here.
// The card poses he peeks over an edge in, and a few gestures sampled at ${FPS} frames a second, for js/minis.js.
export const NUM = ${JSON.stringify(NUM)};
export const CARD = ${JSON.stringify(card)};
export const MOVES = ${JSON.stringify(moves)};
`;
fs.writeFileSync(path.join(here, "../js/blip/moves.js"), out);
console.log(`wrote js/blip/moves.js (${(out.length / 1024).toFixed(1)} KB): ${Object.keys(moves).join(", ")}; poses ${Object.keys(card).join(", ")}`);
